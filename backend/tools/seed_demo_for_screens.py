async def main() -> None:
    async with httpx.AsyncClient(timeout=180) as c:
        # --- accounts -------------------------------------------------
        async def reg(payload):
            r = await c.post(f"{BASE}/auth/register", json=payload)
            if r.status_code != 200:
                r = await c.post(f"{BASE}/auth/login",
                                 json={"email": payload["email"], "password": payload["password"]})
            r.raise_for_status()
            return r.json()
        seller = await reg(SELLER)
        buyer = await reg(BUYER)
        sh = {"Authorization": f"Bearer {seller['token']}"}
        bh = {"Authorization": f"Bearer {buyer['token']}"}
        seller_id = seller["user"]["id"]
        buyer_id = buyer["user"]["id"]
        # tag demo accounts
        await db.users.update_many(
            {"id": {"$in": [seller_id, buyer_id]}}, {"$set": {"demo_screens": True}}
        )
        print("accounts ready")

        # Idempotent: clear any prior demo items/state for these accounts.
        await db.items.delete_many({"seller_id": seller_id})
        await db.tryons.delete_many({"user_id": buyer_id})
        await db.stylist_sessions.delete_many({"user_id": buyer_id})
        await db.orders.delete_many({"buyer_id": buyer_id})
        await db.addresses.delete_many({"user_id": buyer_id})

        # --- generate garment imagery (parallel) ----------------------
        prompts = []
        for row in CATALOG:
            prompts.append(row[6])            # front
            prompts.append(row[7] or None)    # back (may be None)
        flat = [p for p in prompts if p]
        print(f"generating {len(flat)} garment images…")
        results = await asyncio.gather(*[gen_image(p) for p in flat])
        # map back to per-item front/back
        it = iter(results)
        item_imgs = []
        for row in CATALOG:
            front = next(it)
            back = next(it) if row[7] else None
            item_imgs.append((front, back))

        # --- create items via API -------------------------------------
        item_ids = {}
        for (row, (front, back)) in zip(CATALOG, item_imgs):
            name, cat, gtype, price, labels, (cname, chex), *_ = row
            sizes = [{"label": s, "available_qty": 6} for s in labels]
            payload = {
                "name": name, "category": cat, "garment_type": gtype,
                "description": f"{name} — a Nairobi Atelier signature piece.",
                "price_cents": price, "currency": "KES",
                "image_b64": front,
                "extra_images": [back] if back else [],
                "sizes": sizes,
                "colors": [{"name": cname, "hex": chex}],
                "audience": "women",
            }
            r = await c.post(f"{BASE}/items", headers=sh, json=payload)
            r.raise_for_status()
            item_ids[name] = r.json()["id"]
            print("  + item", name)

        dress = item_ids["Terracotta Linen Wrap Dress"]
        heels = item_ids["Strappy Leather Heels"]
        blouse = item_ids["Silk Slip Blouse"]
        trousers = item_ids["High-Waist Tailored Trousers"]
        blazer = item_ids["Ivory Oversized Blazer"]

        # --- try-on result (real Gemini look) -------------------------
        print("generating try-on look (front + back)…")
        tryon_front, tryon_back = await asyncio.gather(
            gen_image("Full-body editorial studio photo of a young African woman with a warm "
                      "medium-brown skin tone wearing a terracotta linen midi wrap dress, "
                      "natural pose, front view, soft neutral studio background, fashion lookbook."),
            gen_image("Full-body editorial studio photo of the same young African woman wearing a "
                      "terracotta linen midi wrap dress, back view, soft neutral studio background."),
        )
        now = datetime.now(timezone.utc)
        tryon_id = str(uuid.uuid4())
        await db.tryons.insert_one({
            "id": tryon_id, "user_id": buyer_id, "item_id": dress,
            "item_name": "Terracotta Linen Wrap Dress",
            "result_image_b64": tryon_front,
            "images": [{"angle": "front", "image_b64": tryon_front},
                       {"angle": "back", "image_b64": tryon_back}],
            "fit_summary": "True to size — we recommend size M for your measurements.",
            "created_at": now,
        })
        print("  tryon id:", tryon_id)

        # --- stylist session (fabricated, references real items) ------
        session_id = str(uuid.uuid4())
        await db.stylist_sessions.insert_one({
            "id": session_id, "user_id": buyer_id, "occasion": "event",
            "appearance_profile": "Warm medium-brown skin with golden undertones; balanced, "
                                  "hourglass proportions — earthy warm tones and defined waistlines flatter beautifully.",
            "messages": [
                {"role": "user", "text": "Style me for a garden wedding I'm attending next month.", "created_at": now},
                {"role": "stylist",
                 "text": "A garden wedding is the perfect excuse for warm, earthy elegance. "
                         "Your golden undertones glow in terracotta and sage — here are two looks I "
                         "styled around pieces available in your size right now.",
                 "outfits": [
                     {"title": "Garden Ceremony", "why": "Terracotta linen echoes your warm undertones; "
                      "the wrap defines your waist, and tan heels elongate the leg.",
                      "item_ids": [dress, heels]},
                     {"title": "Evening Reception", "why": "A sage silk slip with tailored espresso "
                      "trousers and an ivory blazer — relaxed but polished for cooler evening light.",
                      "item_ids": [blouse, trousers, blazer]},
                 ],
                 "created_at": now},
            ],
            "created_at": now, "updated_at": now,
        })
        print("  stylist session:", session_id)

        # --- address --------------------------------------------------
        r = await c.post(f"{BASE}/addresses", headers=bh, json={
            "label": "home", "recipient_name": "Amara W.", "phone": "0712345678",
            "street": "Riverside Drive", "area": "Westlands", "city": "Nairobi",
            "postal_code": "00100", "country": "Kenya", "is_default": True,
        })
        r.raise_for_status()
        addr = r.json()

        # --- order in courier "out for delivery" state ----------------
        order_id = str(uuid.uuid4())
        job_id = str(uuid.uuid4())
        picked = now - timedelta(hours=2)
        ofd = now - timedelta(minutes=40)
        await db.delivery_jobs.insert_one({
            "id": job_id, "order_id": order_id, "seller_id": seller_id,
            "rider_id": "demo-rider", "status": "out_for_delivery",
            "accepted_at": picked - timedelta(minutes=20),
            "picked_up_at": picked, "out_for_delivery_at": ofd,
            "created_at": picked - timedelta(hours=1),
        })
        await db.orders.insert_one({
            "id": order_id, "buyer_id": buyer_id, "seller_id": seller_id,
            "item_id": dress, "item_name": "Terracotta Linen Wrap Dress",
            "size": "M", "color": "Terracotta", "amount_cents": 649000, "currency": "KES",
            "status": "shipped", "session_id": f"demo_{order_id[:8]}",
            "platform_fee_cents": 64900, "seller_net_cents": 584100,
            "cents_normalized": True,
            "delivery_option": "door", "delivery_fee_cents": 30000,
            "delivery_zone_key": "nairobi_inner", "delivery_zone_label": "Inner Nairobi",
            "total_charged_cents": 679000,
            "courier_job_id": job_id, "courier_name": "Brian K.", "courier_phone": "0722113344",
            "courier_requested_at": picked - timedelta(minutes=25),
            "out_for_delivery_at": ofd, "handover_code": "8241",
            "carrier": "Oromona Rider",
            "estimated_delivery_at": now + timedelta(minutes=30),
            "escrow_release_at": now + timedelta(hours=48),
            "shipping_address": {k: addr.get(k) for k in
                                 ("recipient_name", "phone", "street", "area", "city", "postal_code", "country")},
            "cover_image_b64": item_imgs[0][0],
            "created_at": now - timedelta(hours=3),
        })
        print("  order (out for delivery):", order_id)

        print("\nSEED DONE")
        print("BUYER_EMAIL", BUYER["email"])
        print("BUYER_PASSWORD", BUYER["password"])
        print("TRYON_ID", tryon_id)
        print("ITEM_DRESS", dress)
        print("ORDER_ID", order_id)


asyncio.run(main())
